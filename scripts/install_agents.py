#!/usr/bin/env python3
"""
install_agents.py — CodeOps for OpenCode
Generates OpenCode agent Markdown files from codeops/codeops.json routing config.

The generator serves two kinds of roles:

- the twelve catalog roles, generated from templates in `agent-templates/`; and
- project specialists, generated from a project brief in `codeops/specialists/`
  plus one of the two generic specialist templates (`--custom <role>`).

Usage:
  python3 install_agents.py --project <path> --roles ROLE[,ROLE...]
  python3 install_agents.py --project <path> --custom ROLE
  python3 install_agents.py --project <path> --check
  python3 install_agents.py --project <path> --dry-run --roles ROLE[,ROLE...]
"""

